package dev.waterbucket.waterbucketpe.restart;

import dev.waterbucket.waterbucketpe.ProxyServer;
import dev.waterbucket.waterbucketpe.event.defaults.ProxyRestartEvent;
import dev.waterbucket.waterbucketpe.player.ProxiedPlayer;
import dev.waterbucket.waterbucketpe.utils.types.TranslationContainer;
import lombok.Getter;
import lombok.extern.log4j.Log4j2;

import java.io.IOException;
import java.lang.management.ManagementFactory;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermission;
import java.util.Set;
import java.util.concurrent.atomic.AtomicBoolean;

/**
 * Runs the professional restart sequence behind the {@code /restart} command and the panel
 * console: every player is disconnected with a friendly message, plugins are disabled through
 * the normal shutdown path, and a generated relaunch script brings the proxy back with the
 * same JVM options - so newly added plugin jars, packs and config changes are picked up,
 * which an in-process "reload" cannot guarantee.
 * <p>
 * Sequence contract (each step is failure-isolated; the sequence always ends in a clean
 * {@link ProxyServer#shutdown(int)} so operators never end up with a half-dead proxy):
 * <ol>
 *     <li>{@link ProxyRestartEvent} - synchronous, cancellable; plugins may veto.</li>
 *     <li>Broadcast + kick players with the restart messages from lang.ini.</li>
 *     <li>Launch the relaunch script (waits for this process to exit, then starts the new
 *     instance - no port clash) when {@code restart.use_script} is enabled.</li>
 *     <li>Hand over to the standard graceful shutdown.</li>
 * </ol>
 * A restart is a one-shot: the guard flag makes concurrent requests (console spam, panel and
 * console at once, SIGTERM racing in) collapse into the first one.
 */
@Log4j2
public class RestartManager {

    private static final String RESTART_SH = """
            #!/bin/sh
            # Auto-generated by WaterbucketPE. Waits for the previous proxy process to exit,
            # then relaunches it with the same JVM options from the same directory.
            OLD_PID="$1"
            if [ -n "$OLD_PID" ]; then
              while kill -0 "$OLD_PID" 2>/dev/null; do sleep 0.2; done
            fi
            sleep 0.5
            cd %DATA_DIR%
            exec %JAVA_COMMAND%
            """;

    private static final String RESTART_BAT = """
            @echo off
            rem Auto-generated by WaterbucketPE. Waits for the previous proxy process to exit,
            rem then relaunches it with the same JVM options from the same directory.
            :waitloop
            tasklist /FI "PID eq %~1" 2>NUL | find "%~1" >NUL
            if not errorlevel 1 (
              timeout /t 1 /nobreak >NUL
              goto waitloop
            )
            cd /d %DATA_DIR%
            %JAVA_COMMAND%
            """;

    private final ProxyServer proxy;
    private final AtomicBoolean restarting = new AtomicBoolean(false);

    @Getter
    private volatile boolean restartingNow = false;

    public RestartManager(ProxyServer proxy) {
        this.proxy = proxy;
    }

    /**
     * Begins the restart sequence. Returns false when the proxy is already shutting down, a
     * restart is already in progress, or a plugin cancelled the {@link ProxyRestartEvent}.
     *
     * @param initiator who asked for it (console name, player name, "panel"), for the log line
     * @return true when the restart was accepted
     */
    public boolean requestRestart(String initiator) {
        if (!this.proxy.isRunning() || !this.restarting.compareAndSet(false, true)) {
            return false;
        }
        ProxyRestartEvent event = new ProxyRestartEvent(initiator);
        this.proxy.getEventManager().callEvent(event);
        if (event.isCancelled()) {
            // Reset the guard so a later request is not stuck behind a vetoed one
            this.restarting.set(false);
            this.proxy.getLogger().info("Restart requested by {} was cancelled by a plugin", initiator);
            return false;
        }
        this.restartingNow = true;
        this.proxy.getLogger().info("Restart requested by {} - players will be disconnected gracefully", initiator);
        // Run away from the calling thread (console reader, panel executor, player event
        // loop): the sequence sleeps and kicks, the caller must never block on it.
        this.proxy.getScheduler().scheduleTask(this::restartSequence, true);
        return true;
    }

    private void restartSequence() {
        try {
            this.proxy.broadcastMessage(new TranslationContainer("waterbucket.restart.broadcast"));
            Thread.sleep(500); // give the broadcast a moment to flush before kicking

            String kickReason = new TranslationContainer("waterbucket.restart.kick").getTranslated();
            for (ProxiedPlayer player : this.proxy.getPlayerManager().getPlayers().values()) {
                try {
                    player.disconnect(kickReason);
                } catch (Throwable t) {
                    // One stuck player must not stop the restart
                    this.proxy.getLogger().debug("Could not kick player {} during restart: {}",
                            player.getName(), t.toString());
                }
            }
            Thread.sleep(500);

            if (this.proxy.getConfiguration().restartUseScript()) {
                this.launchRelaunchScript();
            } else {
                this.proxy.getLogger().info("restart.use_script is disabled - shutting down without a relaunch script");
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
        } catch (Throwable t) {
            // The sequence must never skip the shutdown: a failure here would leave the proxy
            // running with kicked players and no way back.
            this.proxy.getLogger().error("Restart sequence failed - falling back to a plain shutdown", t);
        }
        this.proxy.shutdown(0);
    }

    /**
     * Generates (when missing) and launches the relaunch script. The script waits for this
     * JVM to exit before starting the new instance, so the listener ports are free again.
     */
    private void launchRelaunchScript() {
        try {
            Path script = this.resolveScriptPath();
            if (script == null) {
                return;
            }
            if (Files.notExists(script)) {
                if (!this.proxy.getConfiguration().restartGenerateScript()) {
                    this.proxy.getLogger().warning("Restart script {} does not exist and restart.generate_script is disabled - shutting down without a relaunch", script);
                    return;
                }
                script = this.generateScript(script);
                if (script == null) {
                    return;
                }
                this.proxy.getLogger().info("Generated restart script {} (edit it to customize the relaunch command)", script);
            }

            String pid = Long.toString(ProcessHandle.current().pid());
            this.proxy.getLogger().info("Executing restart script {} (the new instance starts after PID {} exits)", script, pid);
            new ProcessBuilder(script.toAbsolutePath().toString(), pid)
                    .directory(this.proxy.getDataPath().toFile())
                    .inheritIO()
                    .start();
        } catch (Throwable t) {
            // Security managers, read-only mounts or sandboxed hosts may forbid exec; the
            // plain shutdown still finishes cleanly and the operator's supervisor decides.
            this.proxy.getLogger().warning("Could not execute the restart script ({}); falling back to a plain shutdown - "
                    + "configure your wrapper or service manager to relaunch the proxy", t.toString());
        }
    }

    /**
     * Resolves the script path: the configured {@code restart.script_path} when set (relative
     * paths are resolved against the proxy data folder), otherwise {@code restart.sh} /
     * {@code restart.bat} next to the config depending on the OS.
     */
    Path resolveScriptPath() {
        String configured = this.proxy.getConfiguration().restartScriptPath();
        if (configured != null && !configured.isBlank()) {
            Path path = Path.of(configured);
            if (!path.isAbsolute()) {
                path = this.proxy.getDataPath().resolve(path);
            }
            return path;
        }
        boolean windows = System.getProperty("os.name", "").toLowerCase().contains("win");
        return this.proxy.getDataPath().resolve(windows ? "restart.bat" : "restart.sh");
    }

    /**
     * Writes the relaunch script with the current JVM options and proxy jar. Returns null
     * (with a logged reason) when the environment does not allow generating a working script,
     * e.g. when running from a classes directory instead of the packaged jar.
     */
    Path generateScript(Path target) {
        Path jar = this.locateProxyJar();
        if (jar == null) {
            this.proxy.getLogger().warning("Cannot determine the proxy jar path (running from a directory?) - "
                    + "shutting down without a relaunch script");
            return null;
        }

        String javaCommand = "java " + String.join(" ", ManagementFactory.getRuntimeMXBean().getInputArguments())
                + " -jar \"" + jar + "\"";
        boolean windows = System.getProperty("os.name", "").toLowerCase().contains("win");
        String dataDir = "\"" + this.proxy.getDataPath().toAbsolutePath() + "\"";
        String template = windows ? RESTART_BAT : RESTART_SH;
        String content = template
                .replace("%DATA_DIR%", windows ? dataDir.replace("\"", "") : dataDir)
                .replace("%JAVA_COMMAND%", javaCommand);

        try {
            Files.createDirectories(target.toAbsolutePath().getParent());
            Files.writeString(target.toAbsolutePath(), content, StandardCharsets.UTF_8);
            if (!windows) {
                try {
                    Files.setPosixFilePermissions(target.toAbsolutePath(), Set.of(
                            PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE, PosixFilePermission.OWNER_EXECUTE,
                            PosixFilePermission.GROUP_READ, PosixFilePermission.GROUP_EXECUTE));
                } catch (UnsupportedOperationException ignored) {
                    // Filesystem without POSIX permissions (e.g. Windows mount on a Unix JVM)
                }
            }
            return target.toAbsolutePath();
        } catch (IOException e) {
            this.proxy.getLogger().warning("Could not write the restart script {}: {}", target, e.toString());
            return null;
        }
    }

    /**
     * The running proxy jar, resolved from the class code source. Null outside a packaged
     * deployment (IDE/classes directory runs), where a relaunch script cannot be faithful.
     */
    Path locateProxyJar() {
        try {
            Path location = Path.of(ProxyServer.class.getProtectionDomain().getCodeSource().getLocation().toURI());
            if (Files.isRegularFile(location) && location.getFileName().toString().endsWith(".jar")) {
                return location;
            }
        } catch (Throwable ignored) {
            // Fall through: not a packaged jar run
        }
        return null;
    }

    /**
     * Test seam: run the sequence body directly (the real flow schedules it async).
     */
    void runSequenceForTest() {
        this.restartingNow = true;
        this.restartSequence();
    }

    /**
     * Test seam: the launch step only, without the shutdown hand-over.
     */
    void launchScriptForTest() {
        this.launchRelaunchScript();
    }
}
